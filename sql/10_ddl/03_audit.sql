-- US-1.5: the audit tables in lue_audit. Run as lue_etl by scripts/db_deploy.py. Safe to re-run.
-- The four tables follow the Phase 1 pack exactly (checked by scripts/check_contract.py).
-- Two Phase 2 additions, both required by the development plan:
--   * quarantine_id is an identity column (the pack has a plain BIGINT), so the quarantine engine
--     (US-4.1) does not have to invent ids. Type and NOT NULL are unchanged.
--   * lue_audit.etl_watermark is new (decision O5): the last value loaded per source table, used by
--     the incremental extracts (US-3.2).

-- lue_audit.etl_run_log: One row per pipeline step per run
CREATE TABLE IF NOT EXISTS lue_audit.etl_run_log (
    run_id               BIGINT NOT NULL,
    step                 VARCHAR(40) NOT NULL,
    started_at           TIMESTAMP NOT NULL,
    ended_at             TIMESTAMP,
    rows_read            INT NOT NULL,
    rows_inserted        INT NOT NULL,
    rows_updated         INT NOT NULL,
    rows_rejected        INT NOT NULL,
    status               VARCHAR(10) NOT NULL,
    CONSTRAINT pk_etl_run_log PRIMARY KEY (run_id, step)
);

-- lue_audit.quarantine: One row per rejected source row
CREATE TABLE IF NOT EXISTS lue_audit.quarantine (
    quarantine_id        BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    run_id               BIGINT NOT NULL,
    source_system        VARCHAR(20) NOT NULL,
    source_table         VARCHAR(40) NOT NULL,
    batch_id             BIGINT NOT NULL,
    record               JSONB NOT NULL,
    check_name           VARCHAR(30) NOT NULL,
    rejection_reason     VARCHAR(200) NOT NULL,
    rejected_at          TIMESTAMP NOT NULL,
    CONSTRAINT pk_quarantine PRIMARY KEY (quarantine_id)
);

-- lue_audit.reconciliation: One row per reconciliation check per run
CREATE TABLE IF NOT EXISTS lue_audit.reconciliation (
    run_id               BIGINT NOT NULL,
    check_name           VARCHAR(60) NOT NULL,
    source_value         NUMERIC(16,2) NOT NULL,
    warehouse_value      NUMERIC(16,2) NOT NULL,
    difference           NUMERIC(16,2) NOT NULL,
    passed               BOOLEAN NOT NULL,
    CONSTRAINT pk_reconciliation PRIMARY KEY (run_id, check_name)
);

-- lue_audit.lineage: One row per target table per source table
CREATE TABLE IF NOT EXISTS lue_audit.lineage (
    target_table         VARCHAR(60) NOT NULL,
    source_table         VARCHAR(60) NOT NULL,
    layer_path           VARCHAR(80) NOT NULL,
    transformation       VARCHAR(200) NOT NULL,
    CONSTRAINT pk_lineage PRIMARY KEY (target_table, source_table)
);

-- lue_audit.etl_watermark (not in the pack): one row per source system and source table.
-- last_watermark_value is the newest updated_at (or date) already loaded; the 1900 default means
-- "nothing loaded yet", so the first run reads everything.
CREATE TABLE IF NOT EXISTS lue_audit.etl_watermark (
    source_system        VARCHAR(20) NOT NULL,
    table_name           VARCHAR(60) NOT NULL,
    last_watermark_value TIMESTAMP NOT NULL DEFAULT TIMESTAMP '1900-01-01 00:00:00',
    updated_at           TIMESTAMP NOT NULL DEFAULT now(),
    CONSTRAINT pk_etl_watermark PRIMARY KEY (source_system, table_name)
);
