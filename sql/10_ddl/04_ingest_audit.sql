-- US-3.1 and US-3.3: what the ingestion framework needs in lue_audit. Run as lue_etl by
-- scripts/db_deploy.py. Safe to re-run.
--   * Two sequences: one run_id per pipeline run (etl_run_log, reconciliation, quarantine) and one
--     batch_id per source load (stamped on every bronze row, decision D16).
--   * lue_audit.file_load (not in the pack, like etl_watermark): one row per file and target table
--     per load attempt, with the file's SHA-256. The checksum policy (D16) skips a file whose
--     checksum is already Loaded. The pack's lineage table has no place for a file or a checksum
--     (it is one row per target and source table), so it keeps that meaning.

CREATE SEQUENCE IF NOT EXISTS lue_audit.seq_run_id;
CREATE SEQUENCE IF NOT EXISTS lue_audit.seq_batch_id;

CREATE TABLE IF NOT EXISTS lue_audit.file_load (
    file_load_id         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    run_id               BIGINT NOT NULL,
    batch_id             BIGINT,
    source_system        VARCHAR(20) NOT NULL,
    file_name            VARCHAR(200) NOT NULL,
    checksum_sha256      CHAR(64) NOT NULL,
    target_table         VARCHAR(60) NOT NULL,
    rows_landed          INT NOT NULL,
    status               VARCHAR(10) NOT NULL,
    message              VARCHAR(300),
    loaded_at            TIMESTAMP NOT NULL,
    CONSTRAINT pk_file_load PRIMARY KEY (file_load_id),
    CONSTRAINT ck_file_load_status CHECK (status IN ('Loaded', 'Skipped', 'Rejected'))
);
