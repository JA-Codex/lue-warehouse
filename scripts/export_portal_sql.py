#!/usr/bin/env python3
"""Generate sql/50_reporting/02_owner_portal.sql, the views the owner portal reads (live mode).

    python scripts/export_portal_sql.py            write the file
    python scripts/export_portal_sql.py --check    exit 1 if the file differs from what this script writes

Most portal views are the analytical queries of sql/60_analytics/analytical.sql wrapped in CREATE VIEW, copied
by this script so the portal and the analytics can never disagree: Q2, Q3, Q4a, Q6b, Q7, Q8, Q9a, Q10, Q11,
Q12, Q13, Q14 and W2. Two views are new (owner holdings and the owner's monthly income); they read lue_dw
and lue_reporting only. The file runs after 01_reporting.sql (name order, scripts/db_deploy.py) as lue_etl;
lue_reader reads every view through the schema's default privileges.
"""

# ruff: noqa: E501  (SQL comments and messages: long lines read better)

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "sql" / "60_analytics" / "analytical.sql"
TARGET = ROOT / "sql" / "50_reporting" / "02_owner_portal.sql"

# (query label in analytical.sql, view name, what the portal uses it for)
WRAPPED = [
    ("Q2", "vw_portal_building_arrears", "arrears and billed per building (Q2)"),
    ("Q3", "vw_portal_ageing", "overdue balance by ageing bucket (Q3)"),
    ("Q4a", "vw_portal_late_payers", "tenants who pay late repeatedly (Q4a)"),
    ("Q6b", "vw_portal_move_in_season", "new leases by calendar month (Q6b)"),
    ("Q7", "vw_portal_vacancy_by_type", "vacancy length by unit type (Q7)"),
    ("Q8", "vw_portal_renewal", "lease renewals per building (Q8)"),
    ("Q9a", "vw_portal_vendor_time", "time to resolve by category and vendor (Q9a)"),
    ("Q10", "vw_portal_building_sla", "SLA breaches per building (Q10)"),
    ("Q11", "vw_portal_building_cost", "maintenance cost per unit-month per building (Q11)"),
    ("Q12", "vw_portal_owner_noi", "net operating income per owner (Q12)"),
    ("Q13", "vw_portal_incentives", "vacancy length with and without offers (Q13)"),
    ("Q14", "vw_portal_rain", "leak requests on heavy-rain days (Q14)"),
    ("W2", "vw_portal_monthly_cash", "cash received and cohort collection rate by month (W2)"),
]

NEW_VIEWS = """\
-- ---------------------------------------------------------------------------------------------------------
-- vw_portal_owner_holding: the units each owner held on the window's last day, by building and unit type
-- (Q12 counts the same units per owner: fact_unit_occupancy_daily on the last day)
-- ---------------------------------------------------------------------------------------------------------
CREATE OR REPLACE VIEW lue_reporting.vw_portal_owner_holding AS
SELECT o.owner_code, u.building_code, u.unit_type, count(*)::int AS units
FROM lue_dw.fact_unit_occupancy_daily f
JOIN lue_dw.dim_date d ON d.date_key = f.snapshot_date_key
JOIN lue_dw.dim_owner o ON o.owner_key = f.owner_key
JOIN lue_dw.dim_unit u ON u.unit_key = f.unit_key
CROSS JOIN lue_reporting.vw_reporting_window w
WHERE d.full_date = w.window_end
GROUP BY o.owner_code, u.building_code, u.unit_type;

-- ---------------------------------------------------------------------------------------------------------
-- vw_portal_owner_month: rent, maintenance, fee and NOI per owner and month (mart_owner_portfolio_monthly)
-- ---------------------------------------------------------------------------------------------------------
CREATE OR REPLACE VIEW lue_reporting.vw_portal_owner_month AS
SELECT o.owner_code, m.year_month, x.rent_collected, x.maintenance_cost, x.management_fee, x.noi
FROM lue_reporting.mart_owner_portfolio_monthly x
JOIN lue_reporting.vw_dim_owner o ON o.owner_key = x.owner_key
JOIN lue_reporting.vw_dim_month m ON m.month_key = x.month_key;
"""


def statement(text: str, label: str) -> str:
    """The SQL statement of one labelled query: from its first WITH/SELECT line to the line ending in ';'."""
    m = re.search(rf"^-- {re.escape(label)}\s", text, re.M)
    if not m:
        raise SystemExit(f"{SOURCE.name}: no query labelled {label}")
    tail = text[m.start():]
    start = re.search(r"^(WITH|SELECT)\b", tail, re.M)
    if not start:
        raise SystemExit(f"{SOURCE.name}: no statement after {label}")
    lines = []
    for line in tail[start.start():].splitlines():
        lines.append(line.rstrip())
        if line.rstrip().endswith(";"):
            break
    else:
        raise SystemExit(f"{SOURCE.name}: statement of {label} has no terminating semicolon")
    lines[-1] = lines[-1][:-1]  # drop the ';'; the view adds its own
    return "\n".join(lines)


def render() -> str:
    text = SOURCE.read_text(encoding="utf-8")
    out = [
        "-- sql/50_reporting/02_owner_portal.sql: the views the owner portal reads (live mode)",
        "-- GENERATED by scripts/export_portal_sql.py from sql/60_analytics/analytical.sql: do not edit; change the",
        "-- query there and run  python scripts/export_portal_sql.py  (CI fails while the two differ).",
        "-- Runs in: lue_warehouse, as lue_etl, after 01_reporting.sql (scripts/db_deploy.py, name order). Safe to",
        "-- re-run (CREATE OR REPLACE; 01_reporting.sql drops the layer first, these views included).",
        "-- Access: lue_reader reads every view here (default privileges, sql/00_setup/05_warehouse_schemas.sql).",
        "",
    ]
    for label, view, what in WRAPPED:
        out += [
            "-- " + "-" * 105,
            f"-- {view}: {what}",
            "-- " + "-" * 105,
            f"CREATE OR REPLACE VIEW lue_reporting.{view} AS",
            statement(text, label) + ";",
            "",
        ]
    out.append(NEW_VIEWS)
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if the file is out of date")
    a = ap.parse_args()
    want = render()
    if a.check:
        same = TARGET.is_file() and TARGET.read_text(encoding="utf-8") == want
        print(f"{TARGET.relative_to(ROOT)} is " + ("up to date" if same else "out of date: run python scripts/export_portal_sql.py"))
        return 0 if same else 1
    TARGET.write_text(want, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(ROOT)} ({len(WRAPPED)} wrapped queries, 2 new views)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
