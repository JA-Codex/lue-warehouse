#!/usr/bin/env python3
"""US-9.3: write the dimension and fact load scripts (the brief's "Dimension Load Scripts" and
"Fact Load Scripts", SQL) from the specs the loaders run.

    python scripts/export_load_sql.py           write sql/30_dimensions/02_dimension_loads.sql
                                                and sql/40_facts/01_fact_loads.sql
    python scripts/export_load_sql.py --check   exit 1 if a committed file differs (CI)

The pipeline loads through etl/dimensions/load.py and etl/facts/load.py, which build every
statement from etl/dimensions/spec.py and etl/facts/spec.py. This script renders those same
statements, in the same order, as plain SQL files, so the SQL can be read and run by hand
(psql -f): the loaders' parameters (%(run)s and so on) become session settings set at the top of
each file. --check keeps the files equal to the loaders: a spec change without a re-export fails
make test. What the files cannot do, and the Python loaders do, is said in each file's header.
"""

# ruff: noqa: E501  (SQL text: long lines read better)

from __future__ import annotations

import argparse
import re
import sys
from datetime import date, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from etl.dimensions import load as dload  # noqa: E402
from etl.dimensions import spec as dspec  # noqa: E402
from etl.facts import keys  # noqa: E402
from etl.facts import load as fload  # noqa: E402
from etl.facts import spec as fspec  # noqa: E402

DIM_FILE = ROOT / "sql" / "30_dimensions" / "02_dimension_loads.sql"
FACT_FILE = ROOT / "sql" / "40_facts" / "01_fact_loads.sql"

# The loaders' parameters as session settings (set_config at the top of a file, or per pass).
PARAMS = {
    "run": "current_setting('lue.run_id')::bigint",
    "now": "current_setting('lue.loaded_at')::timestamp",
    "first": "current_setting('lue.first')::date",
    "last": "current_setting('lue.last')::date",
    "first_key": "current_setting('lue.first_key')::int",
    "last_key": "current_setting('lue.last_key')::int",
}
START = (
    "SELECT set_config('lue.run_id', nextval('lue_audit.seq_run_id')::text, false),\n"
    "       set_config('lue.loaded_at', date_trunc('second', localtimestamp)::text, false);"
)


def bind(sql: str) -> str:
    """A statement the loader runs with parameters: each %(name)s becomes its setting, %% is %."""
    out = re.sub(r"%\((\w+)\)s", lambda m: PARAMS[m.group(1)], sql)
    if re.search(r"%\(\w+\)s|%s", out):
        raise ValueError(f"an unbound parameter is left: {out[:120]}")
    return out.replace("%%", "%")


def tidy(sql: str) -> str:
    """Trailing blanks and the loaders' RETURNING (it only feeds their counts) removed."""
    sql = re.sub(r"\s+RETURNING [^;]*$", "", sql.strip())
    return "\n".join(line.rstrip() for line in sql.splitlines()) + ";"


def window(first: date, last: date) -> str:
    """set_config of one pass of a periodic snapshot: its days and their date keys."""
    k = fload._key  # noqa: SLF001  (the loader's own date key)
    return (f"SELECT set_config('lue.first', '{first}', false), set_config('lue.last', '{last}', false),\n"
            f"       set_config('lue.first_key', '{k(first)}', false), set_config('lue.last_key', '{k(last)}', false);")  # fmt: skip


def banner(title: str) -> str:
    return f"-- {'-' * 96}\n-- {title}\n-- {'-' * 96}"


def dimension_sql() -> str:
    parts = [f"""-- sql/30_dimensions/02_dimension_loads.sql: the dimension load scripts (E6, US-6.1 to US-6.5)
-- GENERATED by scripts/export_load_sql.py from etl/dimensions/spec.py: do not edit by hand; change
-- the spec and re-export (make test fails while this file and the loader differ).
--
-- The pipeline runs these statements through etl/dimensions/load.py (python etl/dimensions/run.py),
-- in this order, one transaction per dimension, and adds what plain SQL cannot:
--   * refuses a source with a natural key twice or missing (the step fails, nothing changes);
--   * the SCD2 versions (US-6.2, US-6.3): from each member's history (_dim_hist) Python plans the
--     versions it should have and, per new version, closes the current one and opens the next:
--        UPDATE lue_dw.<dim> SET effective_to = <change date>, is_current = FALSE, batch_id, loaded_at
--          WHERE <key> = <current key>;
--        INSERT INTO lue_dw.<dim> (<natural key, other columns>, <type 2 columns>, effective_from,
--          effective_to, is_current, ...) SELECT ..., <new type 2 values>, <change date>,
--          DATE '{dspec.OPEN_END}', TRUE, ... FROM lue_dw.<dim> WHERE <key> = <current key>;
--     (marked below where it runs; run by hand, this file loads new members with their first state)
--   * the counts in lue_audit.etl_run_log, the lineage, and fresh statistics (ANALYZE).
-- Run by hand on a warehouse with staging loaded (it is one transaction):
--   psql -d lue_warehouse -v ON_ERROR_STOP=1 -f sql/30_dimensions/02_dimension_loads.sql
-- The static dimensions (dim_date, payment method, charge type, lease event type, request flags)
-- are loaded by sql/30_dimensions/01_reference_dimensions.sql (US-1.4).

BEGIN;
{START}

{banner("dim_date: the holiday and Ramadan flags from the S2 register (US-6.4)")}
{tidy(dspec.HOLIDAYS)}"""]
    for d in dspec.DIMS:
        kinds = {t: [c for c, k in d.cols.items() if k == t] for t in (0, 1, 2)}
        about = (f"{d.name} ({d.story}): natural key {', '.join(d.nk)}; surrogate key {d.key} (identity); "
                 f"{'SCD Type 2' if d.scd2 else 'Type 1'}" + (", inferred members" if d.inferred else ""))
        steps = [banner(about),
                 f"-- Type 1 (overwrite): {', '.join(kinds[1]) or 'none'}"
                 + (f"\n-- Type 2 (history):  {', '.join(kinds[2])}" if kinds[2] else "")
                 + (f"\n-- Type 0 (fixed):    {', '.join(kinds[0])}" if kinds[0] else ""),
                 "-- the source: one row per natural key with its current values (staging)",
                 tidy(f"CREATE TEMP TABLE _dim_src ON COMMIT DROP AS {d.source}")]
        if d.scd2 and d.history:
            steps += ["-- its history: every known state with the date it took effect, oldest first",
                      tidy(f"CREATE TEMP TABLE _dim_hist ON COMMIT DROP AS {d.history}")]
        steps += ["-- new members (US-6.1)" + (", with their oldest known state, valid from " + dspec.FIRST_DAY if d.scd2 else ""),
                  tidy(bind(dload.insert_sql(d)))]
        if sql := dload.complete_inferred_sql(d):
            steps += ["-- inferred members whose record has arrived: real values, is_inferred FALSE (US-6.5)", tidy(bind(sql))]
        if d.scd2 and d.history:
            steps.append(f"-- SCD2 versions from _dim_hist: etl/dimensions/load.py apply_scd2 (see the header); Type 2: {', '.join(d.type2)}")
        if sql := dload.type1_sql(d):
            steps += ["-- Type 1: overwrite in place on every version where a value differs", tidy(bind(sql))]
        if sql := dload.inferred_sql(d):
            steps += ["-- inferred members for natural keys staging references but no member has yet (US-6.5)", tidy(bind(sql))]
        steps.append(tidy("DROP TABLE _dim_src" + ("; DROP TABLE _dim_hist" if d.scd2 and d.history else "")).replace("; ", ";\n"))
        parts.append("\n".join(steps))
    parts.append("COMMIT;")
    return "\n\n".join(parts) + "\n"


def fact_sql() -> str:
    first, last = keys.DATA_WINDOW
    parts = [f"""-- sql/40_facts/01_fact_loads.sql: the fact load scripts (E7, US-7.1 to US-7.4)
-- GENERATED by scripts/export_load_sql.py from etl/facts/spec.py: do not edit by hand; change the
-- spec and re-export (make test fails while this file and the loader differ).
--
-- Every fact is synced on its grain, so a rerun inserts, updates and deletes nothing (D14):
--   the source query (staging joined to the dimensions, keys point in time) into _fact_src;
--   rows missing a required measure are rejected (deleted from _fact_src, counted by the loader);
--   DELETE the fact rows whose grain left the source; UPDATE the rows whose values differ (an
--   accumulating snapshot's next milestone); INSERT the grains not in the fact yet.
-- The periodic snapshot (fact_unit_occupancy_daily, US-7.3) is loaded for the data window
-- {first} to {last}, then its last refresh days are deleted and re-derived (the one
-- declared exception of D14). The loader runs it month by month (one partition per statement);
-- here it is one pass over the window, with the same result.
-- The pipeline runs these statements through etl/facts/load.py (python etl/facts/run.py), one
-- transaction per fact, and adds: it refuses a source with a grain twice, or a primary-key column
-- unresolved (-1); counts rejected rows and unresolved keys; reconciles each fact to staging by
-- month (US-7.2); runs the fact tests (sql/90_tests/02_fact_tests.sql); logs to lue_audit.
-- Run by hand after the dimensions (it is one transaction):
--   psql -d lue_warehouse -v ON_ERROR_STOP=1 -f sql/40_facts/01_fact_loads.sql

BEGIN;
{START}"""]
    for f in fspec.FACTS:
        steps = [banner(f"{f.name} ({f.story}): grain {', '.join(f.grain)}")]
        steps += [tidy(sql) for sql in f.prepare]
        if f.period:
            a, b = date.fromisoformat(first), date.fromisoformat(last)
            steps += ["-- the snapshot keeps the data window only",
                      tidy(f"DELETE FROM lue_dw.{f.name} WHERE {f.period} NOT BETWEEN {fload._key(a)} AND {fload._key(b)}"),  # noqa: SLF001
                      "-- one pass over the window", window(a, b)]
        steps += ["-- the source: one row per grain", "DROP TABLE IF EXISTS _fact_src;",
                  tidy(bind(f"CREATE TEMP TABLE _fact_src ON COMMIT DROP AS {f.source}"))]
        if f.required:
            steps += [f"-- rows without {', '.join(f.required)} are rejected",
                      tidy(f"DELETE FROM _fact_src WHERE {' OR '.join(c + ' IS NULL' for c in f.required)}")]
        steps += ["-- sync on the grain: grains gone, values changed, grains new",
                  tidy(bind(fload.delete_sql(f))), tidy(bind(fload.update_sql(f))), tidy(bind(fload.insert_sql(f)))]
        if f.period and f.refresh_days:
            end = date.fromisoformat(last)
            a = max(end - timedelta(days=f.refresh_days - 1), date.fromisoformat(first))
            steps += [f"-- the refresh: the last {f.refresh_days} days deleted and re-derived (D14's declared exception)",
                      window(a, end),
                      tidy(bind(f"DELETE FROM lue_dw.{f.name} WHERE {f.period} BETWEEN %(first_key)s AND %(last_key)s")),
                      "DROP TABLE IF EXISTS _fact_src;",
                      tidy(bind(f"CREATE TEMP TABLE _fact_src ON COMMIT DROP AS {f.source}")),
                      tidy(bind(fload.insert_sql(f)))]
        steps.append("DROP TABLE IF EXISTS _fact_src;")
        parts.append("\n".join(steps))
    parts.append("COMMIT;")
    return "\n\n".join(parts) + "\n"


FILES = {DIM_FILE: dimension_sql, FACT_FILE: fact_sql}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if a committed file differs from the loaders")
    args = ap.parse_args(argv)
    stale = []
    for path, render in FILES.items():
        text = render()
        rel = path.relative_to(ROOT).as_posix()
        if args.check:
            ok = path.is_file() and path.read_text(encoding="utf-8") == text  # text mode: a CRLF checkout (Windows) compares equal
            print(f"  [{'PASS' if ok else 'FAIL'}] {rel} equals what the loaders run")
            stale += [] if ok else [rel]
        else:
            path.write_bytes(text.encode("utf-8"))
            print(f"wrote {rel} ({text.count(chr(10)):,} lines)")
    if stale:
        print(f"re-export: python scripts/export_load_sql.py ({', '.join(stale)})")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
